const m = (hhmm: string) => {
  const [h, mm] = hhmm.split(":").map(Number);
  return h * 60 + mm;
};

type Row = [id: string, ja: string, ko: string, lat: number, lng: number, stay: number, open: string, close: string, cat: Category, pri: 1 | 2 | 3, desc: string];
const spots = (rows: Row[]): Spot[] =>
  rows.map(([id, ja, ko, lat, lng, stay, open, close, category, priority, desc]) => ({
    id, ja, ko, lat, lng, stay, open: m(open), close: m(close), category, priority, desc,
  }));

type SRow = [id: string, ja: string, ko: string, lat: number, lng: number];
const stations = (rows: SRow[]): Station[] => rows.map(([id, ja, ko, lat, lng]) => ({ id, ja, ko, lat, lng }));

